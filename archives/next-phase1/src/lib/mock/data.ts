// 오늘 기준 n일 후(음수면 이전) 날짜를 'YYYY-MM-DD'로 반환
function daysFromNow(n: number): string {
  const date = new Date();
  date.setDate(date.getDate() + n);
  return date.toISOString().slice(0, 10);
}

